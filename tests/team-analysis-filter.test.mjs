import assert from "node:assert/strict"
import { describe, it } from "node:test"
import { renderToStaticMarkup } from "react-dom/server"
import { harness, plain, TEAM_PAGE, TEAM_FILTER as FILTER, nodes, selectorOf, teamOf, dateField, queryButton, readyNotice, render } from "./helpers/analysis-filter-harness.mjs"

const selectionProps = async (h, params = {}) => (await h.page(params, TEAM_PAGE)).props.filters.props
const range = { from: "2026-10-01", to: "2026-10-21" }
const params = { project: "SUN", ...range }

describe("Team analysis strict dates URL", () => {
  it("distinguishes empty initial state, valid complete dates and canonical URL", async () => {
    const h = harness()
    assert.deepEqual(plain(await selectionProps(h)), { project: null, dateRange: null, error: null })
    const { teamAnalysisFilterHref, teamAnalysisFilterResult } = h.load("lib/team-analysis-filter.ts")
    const selection = await selectionProps(h, params)
    assert.deepEqual(plain(selection), { project: "SUN", dateRange: range, error: null })
    const href = teamAnalysisFilterHref(selection)
    assert.equal(href, "/analytics/story-points?project=SUN&from=2026-10-01&to=2026-10-21")
    assert.deepEqual(plain(teamAnalysisFilterResult(Object.fromEntries(new URLSearchParams(href.split("?")[1])))), plain(selection))
    assert.equal(teamAnalysisFilterResult({ project: "SUN", from: "2024-02-29", to: "2024-02-29" }).error, null)
  })
  for (const invalid of [
    { project: "SUN" }, { project: "sun", ...range }, { project: "UNKNOWN", ...range }, { project: ["SUN"], ...range }, { ...range },
    { project: "SUN", from: range.from }, { project: "SUN", to: range.to }, { project: "SUN", from: [range.from], to: range.to },
    { project: "SUN", from: range.from, to: [range.to, range.to] }, { ...params, mode: "dates" }, { ...params, sprint: "6823" }, { ...params, unknown: "1" },
    { ...params, from: "2026-02-29" }, { ...params, from: "2026-10-22" }, { ...params, from: "2026-10-1" }, { ...params, from: "2000-01-01" },
    { ...params, from: "1".repeat(16_385) },
  ]) it(`rejects ${JSON.stringify(invalid).slice(0, 160)} without turning it into an active default scope`, async () => {
    const h = harness()
    const selection = await selectionProps(h, invalid)
    assert.ok(selection.error)
    assert.equal(selection.dateRange, null)
    const tree = h.invoke(h.load(FILTER).TeamAnalysisFilter, selection)
    assert.equal(queryButton(tree).props.disabled, true)
    assert.ok(nodes(tree).some((node) => node.props.role === "alert"))
    tree.props.onSubmit({ preventDefault() {} })
    assert.equal(readyNotice(h.invoke(h.load(FILTER).TeamAnalysisFilter, selection)), false)
    assert.deepEqual(h.pushes, [])
  })
  it("revalidates serializers rather than trusting typed callers", () => {
    const { teamAnalysisFilterHref } = harness().load("lib/team-analysis-filter.ts")
    const valid = { project: "SUN", dateRange: range, error: null }
    for (const invalid of [
      { ...valid, project: null }, { ...valid, project: "UNKNOWN" }, { ...valid, error: "invalid" }, { ...valid, dateRange: null },
      { ...valid, mode: "dates" }, { ...valid, sprint: "6823" }, { ...valid, selectedSprintIds: [] },
      { ...valid, dateRange: { from: "2026-02-30", to: range.to } }, { ...valid, dateRange: { from: "2000-01-01", to: range.to } },
    ]) assert.throws(() => teamAnalysisFilterHref(invalid), /篩選條件無效/)
  })
})

describe("Team date filter controls and placeholder submission", () => {
  it("awaits searchParams, stays ComingSoon and uses no Sprint/mode controls", async () => {
    const h = harness()
    const page = await h.page(params, TEAM_PAGE)
    assert.equal(page.props.title, "團隊分析")
    assert.equal(page.props.showDescription, false)
    assert.equal(page.props.filters.type, h.load(FILTER).TeamAnalysisFilter)
    const tree = h.invoke(page.props.filters.type, page.props.filters.props)
    assert.equal(nodes(tree).some((node) => node.props.type === "radio" || node.props.kind === "sprint"), false)
    const markup = renderToStaticMarkup(tree)
    assert.match(markup, /近1月/)
    assert.match(markup, /近2月/)
    assert.match(markup, /近3月/)
    assert.match(markup, /近6月/)
    assert.match(markup, /分析區間/)
    assert.doesNotMatch(markup, /近7天|近30天/)
    assert.deepEqual(h.pushes, [])
  })
  it("initially gates everything except Project and selects browser-local last calendar month", async () => {
    const h = harness()
    const { TeamAnalysisFilter } = h.load(FILTER)
    const props = await selectionProps(h)
    let tree = h.invoke(TeamAnalysisFilter, props)
    assert.deepEqual(plain(dateField(tree).props.value), { from: "2026-09-22", to: "2026-10-21" })
    assert.equal(tree.props.children[1].props.disabled, true)
    assert.equal(tree.props.children[0].props.children[1].props.inert, true)
    assert.equal(queryButton(tree).props.disabled, true)
    teamOf(tree).props.onGroupsChange(["ent-web"])
    dateField(tree).props.onChange(range)
    dateField(tree).props.onCommit(range)
    tree.props.onSubmit({ preventDefault() {} })
    assert.deepEqual(h.pushes, [])
    assert.equal(readyNotice(h.invoke(TeamAnalysisFilter, props)), false)
    selectorOf(tree).props.onProjectChange("SUN")
    assert.equal(h.pushes.at(-1), "/analytics/story-points?project=SUN&from=2026-09-22&to=2026-10-21")
    tree = h.invoke(TeamAnalysisFilter, props)
    assert.equal(queryButton(tree).props.disabled, false)
    assert.equal(tree.props.children[1].props.disabled, false)
    assert.deepEqual(plain(teamOf(tree).props.groups), [])
  })
  it("never guesses server today or auto-corrects a malformed date URL", async () => {
    const h = harness()
    const { TeamAnalysisFilter } = h.load(FILTER)
    const empty = await selectionProps(h)
    assert.match(render(TeamAnalysisFilter, empty), /正在準備分析區間/)
    const invalid = await selectionProps(h, { ...params, from: "invalid" })
    assert.match(render(TeamAnalysisFilter, invalid), /正在準備分析區間/)
    const tree = h.invoke(TeamAnalysisFilter, invalid)
    assert.equal(queryButton(tree).props.disabled, true)
    const field = dateField(tree)
    h.invoke(field.type, field.props)
    h.flushEffects()
    assert.deepEqual(h.pushes, [])
    field.props.onCommit({ from: "2026-10-22", to: range.to })
    field.props.onCommit({ from: "2000-01-01", to: range.to })
    assert.deepEqual(h.pushes, [])
    field.props.onCommit(range)
    assert.equal(h.pushes.at(-1), "/analytics/story-points?project=SUN&from=2026-10-01&to=2026-10-21")
    assert.equal(queryButton(h.invoke(TeamAnalysisFilter, invalid)).props.disabled, false)
  })
  it("applies each calendar-month shortcut through the shared DateRangeField", async () => {
    const h = harness()
    const { TeamAnalysisFilter } = h.load(FILTER)
    const props = await selectionProps(h, params)
    for (const [label, from] of [["近1月", "2026-09-22"], ["近2月", "2026-08-22"], ["近3月", "2026-07-22"], ["近6月", "2026-04-22"]]) {
      const field = dateField(h.invoke(TeamAnalysisFilter, props))
      const calendar = h.invoke(field.type, field.props)
      h.flushEffects()
      nodes(calendar).find((node) => node.type === "button" && node.props.children === label).props.onClick()
      assert.equal(h.pushes.at(-1), `/analytics/story-points?project=SUN&from=${from}&to=2026-10-21`)
      assert.deepEqual(plain(dateField(h.invoke(TeamAnalysisFilter, props)).props.value), { from, to: range.to })
    }
    assert.equal(h.pushes.length, 4)
  })
  it("commits valid custom dates only, ignores duplicate commits and maintains rapid latest intent", async () => {
    const h = harness()
    const { TeamAnalysisFilter } = h.load(FILTER)
    const props = await selectionProps(h, params)
    const tree = h.invoke(TeamAnalysisFilter, props)
    const field = dateField(tree)
    const sept = { from: "2026-09-01", to: "2026-09-30" }
    field.props.onChange(sept)
    assert.deepEqual(h.pushes, [])
    field.props.onCommit(sept)
    field.props.onCommit(sept)
    field.props.onCommit({ from: "2026-08-01", to: "2026-08-31" })
    assert.deepEqual(h.pushes, ["/analytics/story-points?project=SUN&from=2026-09-01&to=2026-09-30", "/analytics/story-points?project=SUN&from=2026-08-01&to=2026-08-31"])
    assert.equal(dateField(h.invoke(TeamAnalysisFilter, props)).props.value.from, "2026-08-01")
  })
  it("uses latest date drafts for Enter without analytics requests, and invalidates readiness on dates/Team", async () => {
    const h = harness()
    const { TeamAnalysisFilter } = h.load(FILTER)
    const props = await selectionProps(h, params)
    let tree = h.invoke(TeamAnalysisFilter, props)
    const submit = tree.props.onSubmit
    dateField(tree).props.onChange({ from: "2026-09-01", to: "2026-09-30" })
    submit({ preventDefault() {} })
    tree = h.invoke(TeamAnalysisFilter, props)
    assert.equal(readyNotice(tree), true)
    dateField(tree).props.onChange({ from: "2026-09-02", to: "2026-09-30" })
    assert.equal(readyNotice(h.invoke(TeamAnalysisFilter, props)), false)
    submit({ preventDefault() {} })
    tree = h.invoke(TeamAnalysisFilter, props)
    assert.equal(readyNotice(tree), true)
    teamOf(tree).props.onGroupsChange(["ent-web"])
    assert.equal(readyNotice(h.invoke(TeamAnalysisFilter, props)), false)
    assert.deepEqual(h.pushes, [])
  })
  it("preserves Team/date drafts across Project changes, but rejects old Project calendar callbacks", async () => {
    const h = harness()
    const { TeamAnalysisFilter } = h.load(FILTER)
    const props = await selectionProps(h, params)
    let tree = h.invoke(TeamAnalysisFilter, props)
    teamOf(tree).props.onGroupsChange(["ent-web"])
    const sept = { from: "2026-09-01", to: "2026-09-30" }
    dateField(tree).props.onChange(sept)
    selectorOf(tree).props.onProjectChange("TKK")
    assert.equal(h.pushes.at(-1), "/analytics/story-points?project=TKK&from=2026-09-01&to=2026-09-30")
    dateField(tree).props.onChange(range)
    dateField(tree).props.onCommit(range)
    assert.equal(h.pushes.length, 1)
    tree = h.invoke(TeamAnalysisFilter, props)
    assert.deepEqual(plain(dateField(tree).props.value), sept)
    assert.deepEqual(plain(teamOf(tree).props.groups), ["ent-web"])
  })
  it("restores Back/Forward dates, rejects stale same-project calendars and resets Team on reload", async () => {
    const h = harness()
    const { TeamAnalysisFilter } = h.load(FILTER)
    let props = await selectionProps(h, params)
    let tree = h.invoke(TeamAnalysisFilter, props)
    teamOf(tree).props.onGroupsChange(["ent-web"])
    dateField(tree).props.onCommit({ from: "2026-09-01", to: "2026-09-30" })
    const oldTree = tree
    h.setPending(false)
    props = await selectionProps(h, params)
    tree = h.invoke(TeamAnalysisFilter, props)
    assert.deepEqual(plain(dateField(tree).props.value), range)
    dateField(oldTree).props.onChange({ from: "2026-08-01", to: "2026-08-31" })
    dateField(oldTree).props.onCommit({ from: "2026-08-01", to: "2026-08-31" })
    assert.equal(h.pushes.length, 1)
    assert.deepEqual(plain(teamOf(tree).props.groups), ["ent-web"])
    const fresh = harness()
    assert.deepEqual(plain(teamOf(fresh.invoke(fresh.load(FILTER).TeamAnalysisFilter, props)).props.groups), [])
    props = await selectionProps(h)
    tree = h.invoke(TeamAnalysisFilter, props)
    teamOf(oldTree).props.onGroupsChange(["ent-be1"])
    dateField(oldTree).props.onCommit(range)
    assert.equal(queryButton(tree).props.disabled, true)
    assert.equal(tree.props.children[1].props.disabled, true)
    assert.deepEqual(plain(teamOf(h.invoke(TeamAnalysisFilter, props)).props.groups), ["ent-web"])
    assert.equal(h.pushes.length, 1)
  })
  it("reuses central Project/Team/Search widths and shrinkable date layout", async () => {
    const h = harness()
    const props = await selectionProps(h, params)
    const { TeamAnalysisFilter } = h.load(FILTER)
    const tree = h.invoke(TeamAnalysisFilter, props)
    const { FILTER_SELECT_WIDTH_CLASS } = h.load("components/filter-dropdown.tsx")
    const markup = render(TeamAnalysisFilter, props)
    for (const kind of ["project", "team"]) assert.ok(markup.includes(`class="relative ${FILTER_SELECT_WIDTH_CLASS[kind]}"`))
    assert.match(markup, /sr-only[^>]*>（必選）/)
    assert.equal(queryButton(tree).props.className, undefined)
    assert.equal(queryButton(tree).props.style, undefined)
    const native = h.invoke(queryButton(tree).type, queryButton(tree).props)
    assert.match(native.props.className, /w-24/)
    assert.match(native.props.className, /max-w-full/)
    const dateWrapper = nodes(tree).find((node) => node.props.children === dateField(tree))
    assert.match(dateWrapper.props.className, /min-w-0/)
    assert.match(dateWrapper.props.className, /max-w-full/)
    assert.match(tree.props.children[1].props.children[1].props.className, /flex-wrap/)
    assert.equal(teamOf(tree).props.perMember, false)
  })
})
